def build(row):
    questions = {
        f"sub_{i}": {"type": "noul", "instructions": q, "criteria": {"true": t, "false": f}, "polarity": "yes_is_pass"}
        for i, (q, t, f) in enumerate(SUBS[row["id"]])
    }
    return {**{k: row[k] for k in ("id", "review_type", "category", "state", "notes", "context")},
            "aggregation": "all_pass", "questions": questions}


def review_md(rows, labels):
    lines = ["# v3 の問い（意味確認用）", "",
             "行の合格は「すべての小問が Yes」。Opus 欄は記録上の判定（実測で確定したものを含む）。", ""]
    for r in rows:
        lines.append(f"## {r['id']}（Opus: {labels[r['id']]}）")
        lines.append("")
        lines.append(f"- 元の指摘・条件: {labels[r['id'] + ':crit']}")
        for q in r["questions"].values():
            lines.append(f"- {q['instructions']}")
            lines.append(f"  - Yes: {q['criteria']['true']} / No: {q['criteria']['false']}")
        lines.append("")
    return "\n".join(lines)


def main(v2_path, dataset_path, out, review_out):
    v2 = [json.loads(l) for l in open(v2_path, encoding="utf-8")]
    labels = {}
    for l in open(dataset_path, encoding="utf-8"):
        d = json.loads(l)
        g = d.get("ground_truth")
        label = {"measured_false": "合格（実測で指摘は誤り）", "measured_true": "欠陥（実測で確定）"}.get(
            g, {"fail": "欠陥", "pass": "合格"}.get(d["opus_verdict"], d["opus_verdict"]))
        labels[d["id"]] = label
        labels[d["id"] + ":crit"] = f"{d['kind']} / {d['criterion']}"
    rows = [build(r) for r in v2]
    assert len(rows) == len(SUBS)
    with open(out, "w", encoding="utf-8") as fh:
        for r in rows:
            fh.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(review_out, "w", encoding="utf-8") as fh:
        fh.write(review_md(rows, labels) + "\n")
    print(len(rows), sum(len(r["questions"]) for r in rows))


if __name__ == "__main__":
    main(*sys.argv[1:5])
